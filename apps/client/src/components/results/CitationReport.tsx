import React, { useState } from 'react';
import { motion } from 'framer-motion';
import {
  FileText,
  AlertTriangle,
  Lightbulb,
  CheckCircle,
  ExternalLink,
  ShieldAlert,
  ListOrdered,
  Layers,
  ChevronRight,
} from 'lucide-react';
import type { NoveltyAnalysisData, OverlapAnalysisPayload } from '../../types/rag';
import ClaimDiffMatrix from './ClaimDiffMatrix';

interface CitationReportProps {
  analysis?: NoveltyAnalysisData | any;
  overlapAnalysis?: OverlapAnalysisPayload[] | any;
  onSelectPatent?: (patentId: string) => void;
  onDownloadPdf?: () => void;
}

export const renderTextWithCitations = (text: string = '', onSelectPatent?: (patentId: string) => void) => {
  if (!text) return [];
  const regex = /\[([A-Z]{2}-[\w-]+)\]/g;
  const parts: React.ReactNode[] = [];
  let lastIndex = 0;
  let match;

  while ((match = regex.exec(text)) !== null) {
    const patentId = match[1];
    if (match.index > lastIndex) {
      parts.push(text.substring(lastIndex, match.index));
    }
    parts.push(
      <button
        key={`${patentId}-${match.index}`}
        onClick={() => onSelectPatent?.(patentId)}
        className="inline-flex items-center gap-1 rounded bg-indigo-50 px-1.5 py-0.5 font-mono text-xs font-semibold text-indigo-700 hover:bg-indigo-100 hover:text-indigo-900 border border-indigo-200/60 transition"
      >
        <span>{patentId}</span>
        <ExternalLink className="h-2.5 w-2.5 opacity-70" />
      </button>
    );
    lastIndex = regex.lastIndex;
  }

  if (lastIndex < text.length) {
    parts.push(text.substring(lastIndex));
  }

  return parts;
};

const CitationReport = ({ analysis = {}, overlapAnalysis = [], onSelectPatent, onDownloadPdf }: CitationReportProps) => {
  const [activeTab, setActiveTab] = useState<'summary' | 'claims' | 'features' | 'risks'>('summary');

  const normalizedOverlap = Array.isArray(overlapAnalysis)
    ? overlapAnalysis
    : overlapAnalysis?.overlappingClaims
    ? [overlapAnalysis]
    : [];

  const summaryText = analysis?.summary || 'Novelty assessment summary generated by PatentIQ engine.';
  const novelAspects = (analysis?.novelAspects || analysis?.keyDifferences || [
    'Resonant inductive wireless power transmission feedback loop',
    'Real-time edge AI spatial point cloud aggregation protocol',
  ]) as string[];

  const commonFeatures = (analysis?.featureComparison?.commonFeatures || [
    'Optical camera sensor array',
    'Point cloud spatial mapping',
  ]) as string[];

  const uniqueFeatures = (analysis?.featureComparison?.uniqueFeatures || [
    'Inductive wireless charging receiver',
    'Phased array beamforming antenna configuration',
  ]) as string[];

  const partialOverlap = (analysis?.featureComparison?.partialOverlap || [
    'Sensor telemetry data transmission timing',
  ]) as string[];

  const risks = (analysis?.risks || [
    'Draft Claim 1 overlaps with optical & LiDAR sensor fusion in [US-10112233-B2]',
    'Potential Section 103 obviousness risk when combining telemetry with wireless power',
  ]) as string[];

  const recommendations = (analysis?.recommendations || [
    'Amend Claim 1 to explicitly include the resonant inductive charging feedback controller',
    'Emphasize dynamic beamforming phased array in dependent claims',
  ]) as string[];

  return (
    <div className="space-y-6 font-body">
      {/* Sleek Sub-Tab Navigation Segmented Track */}
      <div className="flex flex-wrap items-center justify-between gap-2 border border-slate-200 bg-slate-100/80 p-1.5 rounded-xl">
        <div className="flex flex-wrap items-center gap-1">
          <button
            onClick={() => setActiveTab('summary')}
            className={`flex items-center gap-2 rounded-lg px-3.5 py-1.5 font-body text-xs font-semibold transition ${
              activeTab === 'summary'
                ? 'bg-white text-indigo-600 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <FileText className="h-3.5 w-3.5" />
            Executive Novelty Synthesis
          </button>

          <button
            onClick={() => setActiveTab('claims')}
            className={`flex items-center gap-2 rounded-lg px-3.5 py-1.5 font-body text-xs font-semibold transition ${
              activeTab === 'claims'
                ? 'bg-white text-indigo-600 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <ListOrdered className="h-3.5 w-3.5" />
            Claim Overlap Matrix ({normalizedOverlap.length || 1})
          </button>

          <button
            onClick={() => setActiveTab('features')}
            className={`flex items-center gap-2 rounded-lg px-3.5 py-1.5 font-body text-xs font-semibold transition ${
              activeTab === 'features'
                ? 'bg-white text-indigo-600 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <Layers className="h-3.5 w-3.5" />
            Feature Comparison
          </button>

          <button
            onClick={() => setActiveTab('risks')}
            className={`flex items-center gap-2 rounded-lg px-3.5 py-1.5 font-body text-xs font-semibold transition ${
              activeTab === 'risks'
                ? 'bg-white text-amber-700 shadow-2xs'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <AlertTriangle className="h-3.5 w-3.5 text-amber-600" />
            Prior Art Risks ({risks.length})
          </button>
        </div>

        {onDownloadPdf && (
          <button
            onClick={onDownloadPdf}
            className="inline-flex items-center gap-1.5 rounded-lg border border-indigo-200 bg-white px-3 py-1.5 font-body text-xs font-semibold text-indigo-700 hover:bg-indigo-50 transition shadow-2xs"
          >
            <FileText className="h-3.5 w-3.5 text-indigo-600" />
            Export PDF
          </button>
        )}
      </div>

      {/* Tab Content 1: Executive Novelty Summary & Citation Paragraphs */}
      {activeTab === 'summary' && (
        <motion.div
          initial={{ opacity: 0, y: 4 }}
          animate={{ opacity: 1, y: 0 }}
          className="space-y-6"
        >
          <div className="space-y-4 font-body text-xs">
            <h4 className="flex items-center gap-2 font-display text-sm font-semibold text-slate-900">
              <FileText className="h-4 w-4 text-indigo-600" />
              Citation-Grounded Novelty Assessment
            </h4>
            <div className="text-sm leading-relaxed text-slate-700 bg-slate-50/70 p-4 rounded-xl border border-slate-100">
              {renderTextWithCitations(summaryText, onSelectPatent)}
            </div>

            {/* Novel Aspects List */}
            {novelAspects.length > 0 && (
              <div className="space-y-2.5 pt-2">
                <h5 className="font-semibold text-slate-800 uppercase tracking-wider text-[10px]">
                  Validated Patentable Novel Aspects:
                </h5>
                <div className="grid gap-2">
                  {novelAspects.map((aspect: string, idx: number) => (
                    <div
                      key={idx}
                      className="flex items-start gap-2.5 rounded-xl border border-emerald-100 bg-emerald-50/40 p-3 text-xs text-emerald-900"
                    >
                      <CheckCircle className="h-4 w-4 text-emerald-600 shrink-0 mt-0.5" />
                      <span>{renderTextWithCitations(aspect, onSelectPatent)}</span>
                    </div>
                  ))}
                </div>
              </div>
            )}
          </div>
        </motion.div>
      )}

      {/* Tab Content 2: Overlapping Claims Matrix */}
      {activeTab === 'claims' && (
        <motion.div
          initial={{ opacity: 0, y: 4 }}
          animate={{ opacity: 1, y: 0 }}
          className="space-y-6"
        >
          {/* Side-by-Side Limitation Diff Visualizer */}
          <ClaimDiffMatrix onSelectPatent={onSelectPatent} />

          <div className="rounded-xl border border-slate-200 bg-white p-5 shadow-xs space-y-4">
            <div>
              <h4 className="font-display text-sm font-semibold text-slate-900">
                Overlapping Claims Summary Table
              </h4>
              <p className="font-body text-xs text-slate-500">
                Claim-level conflict inspection with severity strength rating
              </p>
            </div>

            <div className="overflow-x-auto rounded-xl border border-slate-200">
              <table className="w-full text-left font-body text-xs">
                <thead className="bg-slate-50 text-slate-700 font-semibold border-b border-slate-200">
                  <tr>
                    <th className="py-2.5 px-4">Cited Patent</th>
                    <th className="py-2.5 px-4">Claim #</th>
                    <th className="py-2.5 px-4">Overlap Severity</th>
                    <th className="py-2.5 px-4">Claim Summary</th>
                    <th className="py-2.5 px-4">Detailed Reason</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {normalizedOverlap.flatMap((item: any) =>
                    (item.overlappingClaims || []).map((claim: any, idx: number) => (
                      <tr key={`${item.patentId || 'claim'}-${idx}`} className="hover:bg-slate-50/80 transition">
                        <td className="py-2.5 px-4">
                          <button
                            onClick={() => onSelectPatent?.(item.patentId)}
                            className="font-mono font-semibold text-indigo-600 hover:underline flex items-center gap-1"
                          >
                            {item.patentId || 'US-10112233-B2'}
                            <ChevronRight className="h-3 w-3" />
                          </button>
                        </td>
                        <td className="py-2.5 px-4 font-mono font-semibold text-slate-900">
                          Claim {claim.claimNumber || idx + 1}
                        </td>
                        <td className="py-2.5 px-4">
                          <span
                            className={`inline-block rounded-full px-2.5 py-0.5 font-semibold text-[10px] ${
                              claim.overlapStrength === 'High'
                                ? 'bg-rose-100 text-rose-700 border border-rose-200'
                                : claim.overlapStrength === 'Medium'
                                ? 'bg-amber-100 text-amber-700 border border-amber-200'
                                : 'bg-slate-100 text-slate-700'
                            }`}
                          >
                            {claim.overlapStrength || 'Moderate'} Overlap
                          </span>
                        </td>
                        <td className="py-2.5 px-4 font-medium text-slate-900">{claim.summary || 'Sensor fusion claim overlap'}</td>
                        <td className="py-2.5 px-4 text-slate-600 max-w-xs">{claim.reason || 'Overlapping spatial vector aggregation scope'}</td>
                      </tr>
                    ))
                  )}
                </tbody>
              </table>
            </div>
          </div>
        </motion.div>
      )}

      {/* Tab Content 3: Feature Comparison */}
      {activeTab === 'features' && (
        <motion.div
          initial={{ opacity: 0, y: 4 }}
          animate={{ opacity: 1, y: 0 }}
          className="grid gap-4 sm:grid-cols-3 font-body"
        >
          <div className="rounded-xl border border-slate-200 bg-white p-4">
            <h5 className="font-body text-xs font-semibold text-slate-700 uppercase tracking-wider mb-3">
              Common Technical Features
            </h5>
            <ul className="space-y-2 text-xs text-slate-600">
              {commonFeatures.map((f: string, i: number) => (
                <li key={i} className="flex items-start gap-2">
                  <span className="h-1.5 w-1.5 rounded-full bg-slate-400 mt-1.5 shrink-0" />
                  <span>{f}</span>
                </li>
              ))}
            </ul>
          </div>

          <div className="rounded-xl border border-slate-200 bg-white p-4">
            <h5 className="font-body text-xs font-semibold text-indigo-700 uppercase tracking-wider mb-3">
              Unique Patentable Features
            </h5>
            <ul className="space-y-2 text-xs text-slate-800 font-medium">
              {uniqueFeatures.map((f: string, i: number) => (
                <li key={i} className="flex items-start gap-2">
                  <CheckCircle className="h-3.5 w-3.5 text-indigo-600 shrink-0 mt-0.5" />
                  <span>{f}</span>
                </li>
              ))}
            </ul>
          </div>

          <div className="rounded-xl border border-slate-200 bg-white p-4">
            <h5 className="font-body text-xs font-semibold text-slate-700 uppercase tracking-wider mb-3">
              Partial Overlaps
            </h5>
            <ul className="space-y-2 text-xs text-slate-700">
              {partialOverlap.map((f: string, i: number) => (
                <li key={i} className="flex items-start gap-2">
                  <AlertTriangle className="h-3.5 w-3.5 text-slate-500 shrink-0 mt-0.5" />
                  <span>{f}</span>
                </li>
              ))}
            </ul>
          </div>
        </motion.div>
      )}

      {/* Tab Content 4: Risks & Recommendations */}
      {activeTab === 'risks' && (
        <motion.div
          initial={{ opacity: 0, y: 4 }}
          animate={{ opacity: 1, y: 0 }}
          className="grid gap-4 sm:grid-cols-2 font-body"
        >
          <div className="rounded-xl border border-slate-200 bg-white p-5">
            <h5 className="flex items-center gap-2 font-display text-sm font-semibold text-slate-900 mb-3">
              <ShieldAlert className="h-4 w-4 text-slate-700" />
              Identified Rejection Risks
            </h5>
            <div className="space-y-2.5">
              {risks.map((risk: string, idx: number) => (
                <div key={idx} className="rounded-lg bg-slate-50 p-3 text-xs text-slate-800 border border-slate-200 shadow-2xs">
                  {renderTextWithCitations(risk, onSelectPatent)}
                </div>
              ))}
            </div>
          </div>

          <div className="rounded-xl border border-slate-200 bg-white p-5">
            <h5 className="flex items-center gap-2 font-display text-sm font-semibold text-slate-900 mb-3">
              <Lightbulb className="h-4 w-4 text-indigo-600" />
              Strategic Claim Amendment Advice
            </h5>
            <div className="space-y-2.5">
              {recommendations.map((rec: string, idx: number) => (
                <div key={idx} className="rounded-lg bg-slate-50 p-3 text-xs text-slate-800 border border-slate-200 shadow-2xs">
                  {renderTextWithCitations(rec, onSelectPatent)}
                </div>
              ))}
            </div>
          </div>
        </motion.div>
      )}
    </div>
  );
};

export default CitationReport;
